// Reads seed/trucks.csv and seed/menu_items.csv and checks every value.
// Used by the seed generator and by the database tests.

import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const seedDir = new URL("../../seed/", import.meta.url);

/** Minimal CSV reader: commas, double-quoted fields, "" for a quote. */
export function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;

  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') {
        field += '"';
        i += 1;
      } else if (ch === '"') {
        quoted = false;
      } else {
        field += ch;
      }
    } else if (ch === '"') {
      quoted = true;
    } else if (ch === ",") {
      row.push(field);
      field = "";
    } else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i += 1;
      row.push(field);
      field = "";
      if (row.length > 1 || row[0] !== "") rows.push(row);
      row = [];
    } else {
      field += ch;
    }
  }
  if (field !== "" || row.length > 0) {
    row.push(field);
    rows.push(row);
  }

  const [header, ...body] = rows;
  return body.map((cells) => {
    if (cells.length !== header.length) {
      throw new Error(`CSV row has ${cells.length} cells, expected ${header.length}: ${cells.join(",")}`);
    }
    return Object.fromEntries(header.map((name, i) => [name, cells[i]]));
  });
}

function read(name) {
  return parseCsv(readFileSync(new URL(name, seedDir), "utf8").replace(/^﻿/, ""));
}

function fail(file, id, message) {
  throw new Error(`${file} ${id}: ${message}`);
}

/** The six trucks, validated. IDs, names and capacities are kept as supplied. */
export function loadTrucks() {
  return read("trucks.csv").map((r) => {
    const capacity = Number(r.default_slot_capacity);
    if (!/^T\d{2}$/.test(r.truck_id)) fail("trucks.csv", r.truck_id, "unexpected truck_id");
    if (!Number.isInteger(capacity) || capacity < 1 || capacity > 20) {
      fail("trucks.csv", r.truck_id, "default_slot_capacity must be 1 to 20");
    }
    return {
      id: r.truck_id,
      name: r.name,
      cuisine: r.cuisine,
      blurb: r.blurb,
      slot_capacity: capacity,
    };
  });
}

/** The 30 dishes, validated. Prices stay as text ("1.950") so no digit is lost. */
export function loadMenuItems() {
  return read("menu_items.csv").map((r) => {
    if (!/^M\d{3}$/.test(r.item_id)) fail("menu_items.csv", r.item_id, "unexpected item_id");
    if (!/^\d+\.\d{3}$/.test(r.price_kwd)) fail("menu_items.csv", r.item_id, "price_kwd needs 3 decimals");
    if (r.sold_out !== "true" && r.sold_out !== "false") {
      fail("menu_items.csv", r.item_id, "sold_out must be true or false");
    }
    return {
      id: r.item_id,
      truck_id: r.truck_id,
      name: r.name,
      category: r.category,
      price_kwd: r.price_kwd,
      description: r.description === "" ? null : r.description,
      sold_out: r.sold_out === "true",
    };
  });
}

export const seedSqlPath = fileURLToPath(new URL("../../supabase/seed.sql", import.meta.url));

const text = (value) => (value === null ? "null" : `'${value.replaceAll("'", "''")}'`);

/** The full text of supabase/seed.sql, built from the two CSVs. */
export function buildSeedSql() {
  const trucks = loadTrucks();
  const items = loadMenuItems();

  const truckRows = trucks
    .map((t) => `  (${text(t.id)}, ${text(t.name)}, ${text(t.cuisine)}, ${text(t.blurb)}, ${t.slot_capacity})`)
    .join(",\n");

  const itemRows = items
    .map(
      (m) =>
        `  (${text(m.id)}, ${text(m.truck_id)}, ${text(m.name)}, ${text(m.category)}, ${m.price_kwd}, ${text(m.description)}, ${m.sold_out})`,
    )
    .join(",\n");

  return `-- GENERATED by scripts/build-seed.mjs from seed/trucks.csv and
-- seed/menu_items.csv. Do not edit by hand: change the CSV and run
-- \`pnpm db:seed:build\`.
--
-- Safe to run more than once. Rows that already exist are left alone, so
-- re-seeding never overwrites a price or sold-out switch a vendor changed.

insert into public.trucks (id, name, cuisine, blurb, slot_capacity)
values
${truckRows}
on conflict (id) do nothing;

insert into public.menu_items (id, truck_id, name, category, price_kwd, description, sold_out)
values
${itemRows}
on conflict (id) do nothing;
`;
}
